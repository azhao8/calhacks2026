export const TASTE_LABELS: readonly string[] = [...GENRE_LABELS, ...SCENE_LABELS, ...MOOD_LABELS];

const LABEL_SET = new Set(TASTE_LABELS);

export function isTasteLabel(label: string): boolean {
  return LABEL_SET.has(label);
}

// Lowercases and trims a label Claude returned; null when it isn't on the list.
export function canonicalLabel(label: string): string | null {
  const cleaned = label.trim().toLowerCase().replace(/[-–—]/g, " ").replace(/\s+/g, " ");
  return LABEL_SET.has(cleaned) ? cleaned : null;
}
